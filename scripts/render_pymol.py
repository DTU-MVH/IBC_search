"""Render a scored structure with PyMOL: cartoon inside a translucent surface.

Writes the motif score into the **B-factor column** of a PDB and drives
PyMOL from a generated script. Putting the score in the B-factor is what
makes the result portable: any viewer -- PyMOL, ChimeraX, Mol*, VMD -- can
colour the structure from that file with one command, with no dependency on
this code.

Residues that were never in an emitted motif carry a sentinel
(``--unscored-value``) rather than zero. Zero would sit in the middle of the
real score range and read as "scored, unremarkable", when the truth is that
the residue was never assessed. The sentinel lets a viewer grey them out
explicitly, and this script does.

The figure is a cartoon coloured by score, wrapped in a transparent grey
surface, so the fold and the called regions stay readable while the surface
still shows the shape an antibody would actually meet.
"""

from __future__ import annotations

import argparse
import csv
import gzip
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

import biotite.structure.io.pdb as pdb_io
import biotite.structure.io.pdbx as pdbx_io

DEFAULT_PYMOL = Path("/Applications/PyMOL.app/Contents/bin/pymol")

PML = """\
# generated by scripts/render_pymol.py -- safe to edit and re-run by hand
load {pdb}, mol
hide everything
bg_color {bg}
set ray_opaque_background, 1
set ray_shadows, 0
set antialias, 2
set surface_quality, 1
set cartoon_transparency, 0.0
set transparency, {surface_transparency}
set two_sided_lighting, on
set specular, 0.15

# --- translucent grey surface: the shape an antibody meets -----------------
show surface, mol
color grey70, mol

# --- cartoon, coloured by the score carried in the B-factor ---------------
show cartoon, mol
set cartoon_fancy_helices, 1
# PyMOL's property selectors understand < and > but NOT >=, and an
# unsupported operator selects nothing without raising -- so the comparisons
# below are strict, with the bounds nudged instead.
select unscored, mol and b < {sentinel_cut}
select below,    mol and b > {sentinel_cut} and b < {threshold}
select called,   mol and b > {threshold_low}
print "called atoms:", cmd.count_atoms("called"), " below:", cmd.count_atoms("below"), " unscored:", cmd.count_atoms("unscored")
color grey85, unscored
color grey45, below
color firebrick, called

{epitope_block}
delete unscored
delete below
delete called

set surface_color, grey70
orient mol
zoom mol, 3
{extra}
ray {width}, {height}
png {png}, dpi={dpi}
save {pse}
"""

# Colouring the epitope on top of the score hides the overlap: a residue that
# is both called and epitope ends up the same colour as one that is epitope
# and missed, so a true positive cannot be told from a false negative. The
# confusion mode gives each of the four outcomes its own colour instead.
#
# Hues are the first three slots of the validated categorical palette plus
# grey -- those three clear the colour-vision gates under all-pairs
# comparison, which is what this figure needs since any pair may be compared.
CONFUSION_BLOCK = """\
select epitope,  mol and ({epitope_sel})
select tp, mol and epitope and b > {threshold_low}
select fn, mol and epitope and b < {threshold}
select fp, mol and not epitope and b > {threshold_low}
color 0x1baf7a, tp
color 0x2a78d6, fn
color 0xeb6834, fp
show spheres, (tp or fn) and name CA
set sphere_scale, {sphere_scale:.3f}, (tp or fn) and name CA
print "TP:", cmd.count_atoms("tp and name CA"), " FP:", cmd.count_atoms("fp and name CA"), " FN:", cmd.count_atoms("fn and name CA")
delete epitope
delete tp
delete fn
delete fp
"""

EPITOPE_BLOCK = """\
# Epitope marked by SHAPE, not colour, so the score colouring survives:
# a sphere means "antibody contact", its colour still means "called or not".
#
# The sphere has to out-read the cartoon it sits on, and it cannot do it by
# colour -- it carries the score's colour, which is the whole point. So it
# does it by SIZE: at the old 0.30 the sphere was thinner than the ribbon
# and simply disappeared into it, worst of all on an all-grey structure
# where sphere and cartoon were the same shade. Scaled past the ribbon's
# width the silhouette breaks the cartoon outline, and the epitope reads as
# beads on a string whatever colour the score gives it.
select epitope, mol and ({epitope_sel})
show spheres, epitope and name CA
set sphere_scale, {sphere_scale:.3f}, epitope and name CA
print "epitope CA spheres:", cmd.count_atoms("epitope and name CA")
delete epitope
"""


def write_scored_pdb(
    structure: Path,
    scores: dict[tuple[str, int], float],
    out_pdb: Path,
    unscored_value: float,
) -> tuple[int, int]:
    """Copy the structure with each atom's B-factor set to its residue score."""
    # The RCSB cache stores entries gzipped, as served. Open through gzip
    # rather than refusing them, so a structure can be rendered straight from
    # the cache the scan already populated.
    name = structure.name.lower()
    if name.endswith(".gz"):
        opener, name = lambda: gzip.open(structure, "rt"), name[:-3]
    else:
        opener = lambda: open(structure, "r")  # noqa: E731
    with opener() as fh:
        if name.endswith((".cif", ".mmcif")):
            array = pdbx_io.get_structure(
                pdbx_io.CIFFile.read(fh), model=1, extra_fields=["b_factor"]
            )
        else:
            array = pdb_io.PDBFile.read(fh).get_structure(
                model=1, extra_fields=["b_factor"]
            )
    array = array[array.element != "H"]

    b = np.full(array.array_length(), float(unscored_value))
    hit = 0
    for i, (chain, res_id) in enumerate(zip(array.chain_id, array.res_id)):
        z = scores.get((str(chain), int(res_id)))
        if z is not None:
            b[i] = float(z)
            hit += 1
    array.set_annotation("b_factor", b)

    out_pdb.parent.mkdir(parents=True, exist_ok=True)
    f = pdb_io.PDBFile()
    f.set_structure(array)
    f.write(str(out_pdb))
    return hit, array.array_length()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("structure", type=Path)
    ap.add_argument("scores_tsv", type=Path,
                    help="TSV with chain, res_id and a score column")
    ap.add_argument("-o", "--out", type=Path, required=True, help="output PNG")
    ap.add_argument("--instance", default=None,
                    help="filter scores_tsv to this instance, if it has that column")
    ap.add_argument("--score-column", default="max_motif_z")
    ap.add_argument("--threshold", type=float, default=1.7)
    ap.add_argument("--epitope-column", default="is_epitope")
    ap.add_argument("--unscored-value", type=float, default=-9.0)
    ap.add_argument("--surface-transparency", type=float, default=0.72)
    ap.add_argument("--sphere-scale", type=float, default=0.425,
                    help="CA sphere radius as a fraction of the van der Waals "
                         "radius; below about 0.35 it stops clearing the "
                         "cartoon loop width and vanishes into the ribbon [0.425]")
    ap.add_argument("--width", type=int, default=1600)
    ap.add_argument("--height", type=int, default=1400)
    ap.add_argument("--dpi", type=int, default=300)
    ap.add_argument("--bg", default="white")
    ap.add_argument("--pymol", type=Path, default=DEFAULT_PYMOL)
    ap.add_argument("--extra", default="", help="extra PyMOL commands before ray")
    ap.add_argument("--no-epitope", action="store_true")
    ap.add_argument("--mode", choices=("prediction", "confusion"),
                    default="prediction",
                    help="confusion: a colour per TP/FP/FN/TN outcome. "
                         "prediction: cartoon by score alone, epitope "
                         "marked by CA spheres only [prediction]")
    args = ap.parse_args(argv)

    pymol = args.pymol if args.pymol.is_file() else shutil.which("pymol")
    if not pymol:
        print(f"error: PyMOL not found at {args.pymol} and not on PATH.\n"
              "  Pass --pymol /path/to/pymol.", file=sys.stderr)
        return 2

    scores: dict[tuple[str, int], float] = {}
    epitope: list[tuple[str, int]] = []
    with args.scores_tsv.open() as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            if args.instance and r.get("instance") not in (None, args.instance):
                continue
            try:
                key = (r["chain"], int(r["res_id"]))
            except (KeyError, ValueError):
                continue
            if args.score_column in r and r[args.score_column] not in ("", None):
                try:
                    scores[key] = float(r[args.score_column])
                except ValueError:
                    pass
            if r.get(args.epitope_column) == "1":
                epitope.append(key)
    if not scores:
        print("error: no scores read", file=sys.stderr)
        return 2

    out: Path = args.out
    pdb = out.with_suffix(".scored.pdb")
    pml = out.with_suffix(".pml")
    pse = out.with_suffix(".pse")
    scored_atoms, total_atoms = write_scored_pdb(
        args.structure, scores, pdb, args.unscored_value
    )

    if epitope and not args.no_epitope:
        by_chain: dict[str, list[int]] = {}
        for chain, res_id in epitope:
            by_chain.setdefault(chain, []).append(res_id)
        sel = " or ".join(
            f"(chain {c} and resi {'+'.join(str(i) for i in sorted(v))})"
            for c, v in sorted(by_chain.items())
        )
        if args.mode == "confusion":
            epitope_block = CONFUSION_BLOCK.format(
                epitope_sel=sel, threshold=args.threshold,
                threshold_low=args.threshold - 1e-4,
                sphere_scale=args.sphere_scale,
            )
        else:
            epitope_block = EPITOPE_BLOCK.format(
                epitope_sel=sel, sphere_scale=args.sphere_scale,
            )
    else:
        epitope_block = ""

    pml.write_text(PML.format(
        pdb=pdb.name, png=out.name, pse=pse.name, bg=args.bg,
        threshold=args.threshold,
        sentinel_cut=args.unscored_value + 0.5,
        threshold_low=args.threshold - 1e-4,
        surface_transparency=args.surface_transparency,
        width=args.width, height=args.height, dpi=args.dpi,
        epitope_block=epitope_block, extra=args.extra,
    ))

    # Run from the output directory so the script's relative names resolve.
    proc = subprocess.run([str(pymol), "-cq", pml.name], cwd=out.parent,
                          capture_output=True, text=True)
    if proc.returncode != 0 or not out.is_file():
        print(f"error: PyMOL failed (rc={proc.returncode})\n"
              f"{(proc.stderr or proc.stdout)[-800:]}", file=sys.stderr)
        return 2

    n_called = sum(1 for z in scores.values() if z >= args.threshold)
    print(f"wrote {out}")
    print(f"  {pdb.name}  score in the B-factor column "
          f"({scored_atoms}/{total_atoms} atoms scored, "
          f"unscored = {args.unscored_value})")
    print(f"  {pml.name}  PyMOL script   {pse.name}  session")
    print(f"  {len(scores)} residues scored, {n_called} at or above "
          f"{args.threshold:+.1f}, {len(set(epitope))} epitope residues marked")
    return 0


if __name__ == "__main__":
    sys.exit(main())
